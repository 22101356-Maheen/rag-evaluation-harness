from sqlalchemy.orm import Session

from backend.app.models.experiment_run import ExperimentRun


# -----------------------------
# Experiment Result Saving
# -----------------------------

def save_experiment_run(
    db: Session,
    project_id: int,
    best_experiment: dict,
    evaluation_dataset_id: int | None = None,
    generation_model: str | None = None,
    evaluator_model: str | None = None,
) -> ExperimentRun:
    """
    Save the winning experiment result for a project.
    """

    configuration = best_experiment["configuration"]
    metrics = best_experiment["metrics"]
    answer_metrics = best_experiment.get("answer_metrics", {})

    # this creates a database record from the winning configuration.
    experiment_run = ExperimentRun(
        project_id=project_id,
        strategy=configuration["strategy"],
        chunk_size=configuration["chunk_size"],
        chunk_overlap=configuration["chunk_overlap"],
        top_k=configuration["top_k"],
        hit_at_k=metrics["hit_at_k"],
        precision_at_k=metrics["precision_at_k"],
        recall_at_k=metrics["recall_at_k"],
        mrr=metrics["mrr"],
        evaluation_dataset_id=evaluation_dataset_id,
        generation_model=generation_model,
        evaluator_model=evaluator_model,
        faithfulness=answer_metrics.get("faithfulness"),
        relevance=answer_metrics.get("relevance"),
        correctness=answer_metrics.get("correctness"),
        hallucination=answer_metrics.get("hallucination"),
    )

    # this saves the experiment result permanently in PostgreSQL.
    db.add(experiment_run)
    try:
        db.commit()
    except Exception:
        db.rollback()
        raise

    # this reloads values generated by PostgreSQL, like the run ID.
    db.refresh(experiment_run)

    return experiment_run
